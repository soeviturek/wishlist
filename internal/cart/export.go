package cart

import (
	"fmt"
	"math"
	"sort"
	"strings"
	"time"

	"wishlist-tracker/internal/models"
)

type storeGroup struct {
	store string
	items []models.CartItem
}

type summary struct {
	quantity int
	unknown  int
	cents    int64
}

func summarize(items []models.CartItem) summary {
	var result summary
	for _, item := range items {
		result.quantity += item.Quantity
		if item.CurrentPrice == nil {
			result.unknown += item.Quantity
		} else {
			result.cents += lineCents(item)
		}
	}
	return result
}

func lineCents(item models.CartItem) int64 {
	return int64(math.Round(*item.CurrentPrice*100)) * int64(item.Quantity)
}

func money(cents int64) string {
	return fmt.Sprintf("$%d.%02d", cents/100, cents%100)
}

func groupItems(items []models.CartItem) []storeGroup {
	sorted := append([]models.CartItem(nil), items...)
	sort.SliceStable(sorted, func(i, j int) bool {
		return strings.ToLower(sorted[i].Store) < strings.ToLower(sorted[j].Store)
	})
	var groups []storeGroup
	for _, item := range sorted {
		if len(groups) == 0 || groups[len(groups)-1].store != item.Store {
			groups = append(groups, storeGroup{store: item.Store})
		}
		last := &groups[len(groups)-1]
		last.items = append(last.items, item)
	}
	return groups
}

func totalLabel(total summary) string {
	if total.unknown > 0 {
		return "Known subtotal"
	}
	return "Estimated total"
}

func RenderText(items []models.CartItem, now time.Time) string {
	groups := groupItems(items)
	total := summarize(items)
	var text strings.Builder
	fmt.Fprintf(&text, "SHOPPING LIST\n%s\n%d products | %d items | %d stores\n\n",
		now.Format("02 Jan 2006, 15:04 MST"), len(items), total.quantity, len(groups))
	for _, group := range groups {
		fmt.Fprintf(&text, "%s\n", group.store)
		for _, item := range group.items {
			fmt.Fprintf(&text, "[ ] %s x%d", strings.Join(strings.Fields(item.Name), " "), item.Quantity)
			if item.CurrentPrice == nil {
				text.WriteString(" - price unavailable\n")
			} else {
				fmt.Fprintf(&text, " - %s each - %s\n", money(int64(math.Round(*item.CurrentPrice*100))), money(lineCents(item)))
			}
		}
		subtotal := summarize(group.items)
		fmt.Fprintf(&text, "%s: %s\n\n", totalLabel(subtotal), money(subtotal.cents))
	}
	fmt.Fprintf(&text, "%s: %s\n", totalLabel(total), money(total.cents))
	if total.unknown > 0 {
		fmt.Fprintf(&text, "Prices unavailable for %d item(s); not included in the subtotal.\n", total.unknown)
	}
	text.WriteString("\nPrices are last recorded estimates and may change in store.\nGenerated by Wishlist Tracker\n")
	return text.String()
}
