func TestTextExportGroupingTotalsAndMissingPrices(t *testing.T) {
	milk, vitamins, free := 2.25, 12.10, 0.0
	items := []models.CartItem{
		{SavedProduct: models.SavedProduct{Name: "Milk", Store: "Woolworths", CurrentPrice: &milk}, Quantity: 3},
		{SavedProduct: models.SavedProduct{Name: "Vitamins", Store: "Chemist Warehouse", CurrentPrice: &vitamins}, Quantity: 2},
		{SavedProduct: models.SavedProduct{Name: "Mystery", Store: "Woolworths"}, Quantity: 1},
		{SavedProduct: models.SavedProduct{Name: "Free sample", Store: "iHerb", CurrentPrice: &free}, Quantity: 3},
	}
	text := RenderText(items, time.Date(2026, 11, 13, 4, 5, 0, 0, time.UTC))
	for _, expected := range []string{
		"4 products | 9 items | 3 stores",
		"[ ] Milk x3 - $2.25 each - $6.75",
		"[ ] Vitamins x2 - $12.10 each - $24.20",
		"[ ] Mystery x1 - price unavailable",
		"[ ] Free sample x3 - $0.00 each - $0.00",
		"Known subtotal: $30.95",
		"Prices unavailable for 1 item(s)",
		"Generated by Wishlist Tracker",
	} {
		if !strings.Contains(text, expected) {
			t.Errorf("missing %q in export:\n%s", expected, text)
		}
	}
	if strings.Index(text, "Chemist Warehouse") > strings.Index(text, "iHerb") ||
		strings.Index(text, "iHerb") > strings.Index(text, "Woolworths") {
		t.Error("stores should have consistent alphabetical grouping")
	}
	if items[0].Name != "Milk" {
		t.Error("export must not reorder the caller's cart")
	}
}

func TestImageExportPortraitWatermarkAndMissingPhoto(t *testing.T) {
	price := 3.25
	items := []models.CartItem{{
		SavedProduct: models.SavedProduct{ID: "milk", Name: "Milk with a long descriptive product name for a useful shopping reminder", Store: "Woolworths", CurrentPrice: &price},
		Quantity:     2,
	}}
	data, missing, err := RenderPNG(context.Background(), items, time.Now().UTC())
	if err != nil {
		t.Fatal(err)
	}
	if missing != 1 {
		t.Fatalf("missing photos must be reported, got %d", missing)
	}
	exported, err := png.Decode(bytes.NewReader(data))
	if err != nil {
		t.Fatal(err)
	}
	bounds := exported.Bounds()
	if bounds.Dy() <= bounds.Dx() {
		t.Fatalf("expected a portrait image, got %v", bounds)
	}
	bearFound := false
	for y := bounds.Max.Y - 160; y < bounds.Max.Y-90 && !bearFound; y++ {
		for x := bounds.Min.X; x < bounds.Max.X; x++ {
			r, g, b, _ := exported.At(x, y).RGBA()
			if r>>8 > 120 && r>>8 < 160 && g>>8 > 65 && g>>8 < 110 && b>>8 > 55 && b>>8 < 100 {
				bearFound = true
				break
			}
		}
	}
	if !bearFound {
		t.Error("the bear logo should appear in the footer watermark")
	}
}

func TestImageExportRejectsOversizedList(t *testing.T) {
	items := make([]models.CartItem, 300)
	for i := range items {
		items[i] = models.CartItem{SavedProduct: models.SavedProduct{Name: "Product", Store: "Woolworths"}, Quantity: 1}
	}
	_, _, err := RenderPNG(context.Background(), items, time.Now().UTC())
	if !errors.Is(err, ErrImageTooLarge) {
		t.Fatalf("oversized exports should return a useful error rather than truncate the list: %v", err)
	}
}

func TestProductPhotoURLValidation(t *testing.T) {
	for _, raw := range []string{
		"https://cdn0.woolworths.media/product.jpg",
		"//static.chemistwarehouse.com.au/product.png",
		"https://cloudinary.images-iherb.com/image.jpg",
		"https://cdn.productimages.coles.com.au/productimages/3/3214780.jpg",
	} {
		if _, err := safeImageURL(raw); err != nil {
			t.Errorf("retailer image %q should be supported: %v", raw, err)
		}
	}
	for _, raw := range []string{
		"http://cdn0.woolworths.media/product.jpg",
		"https://127.0.0.1/product.png",
		"https://cdn0.woolworths.media.invalid/product.png",
		"https://cdn.productimages.coles.com.au.invalid/product.jpg",
		"https://example.com/woolworths.media/product.png",
		"https://user:pass@cdn0.woolworths.media/product.png",
		"https://cdn0.woolworths.media:8443/product.png",
		"file:///private.png",
	} {
		if _, err := safeImageURL(raw); err == nil {
			t.Errorf("untrusted image URL %q must be rejected", raw)
		}
	}
}

type photoTransport func(*http.Request) (*http.Response, error)

func (f photoTransport) RoundTrip(req *http.Request) (*http.Response, error) { return f(req) }

func TestProductPhotoResolvesRelativeSources(t *testing.T) {
	var data bytes.Buffer
	if err := png.Encode(&data, image.NewRGBA(image.Rect(0, 0, 2, 2))); err != nil {
		t.Fatal(err)
	}
	for _, source := range []string{"/photo.png", "//www.chemistwarehouse.com.au/photo.png"} {
		client := &http.Client{Transport: photoTransport(func(req *http.Request) (*http.Response, error) {
			if req.URL.String() != "https://www.chemistwarehouse.com.au/photo.png" {
				t.Errorf("unexpected photo URL: %s", req.URL.String())
			}
			return &http.Response{StatusCode: http.StatusOK, Body: io.NopCloser(bytes.NewReader(data.Bytes()))}, nil
		})}
		photo, err := loadProductImage(context.Background(), client, source, "https://www.chemistwarehouse.com.au/buy/1/product")
		if err != nil || photo.Bounds().Dx() != 2 || photo.Bounds().Dy() != 2 {
			t.Fatalf("relative product photo %q failed to decode: %v", source, err)
		}
	}
}
